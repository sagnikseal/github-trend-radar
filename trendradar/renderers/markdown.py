def generate_markdown(reports: list[TrendReport], ideas: list[ProjectIdea]) -> str:
    """Generate a comprehensive GitHub-flavored Markdown trends report."""
    now = datetime.utcnow()
    lines: list[str] = []

    lines += [
        "# 📡 GitHub Trend Radar",
        "",
        "> **Auto-generated by [github-trend-radar](https://github.com) · "
        f"Updated {now.strftime('%Y-%m-%d %H:%M UTC')}**",
        "",
        "[![Daily Update](https://github.com/actions/workflows/daily-radar.yml/badge.svg)](../../actions/workflows/daily-radar.yml)",
        "",
        "Real-time GitHub demand intelligence: tracks star velocity, identifies breakout repositories,",
        "and generates actionable personal project blueprints.",
        "",
        "---",
        "",
        "## 🔥 Velocity Breakdown",
        "",
        "| Tier | Stars/Day Threshold | Meaning |",
        "| --- | --- | --- |",
        "| 🚀 BREAKING | ≥ 100 | Explosive momentum — act now |",
        "| ⚡ HIGH VELOCITY | ≥ 20 | Strong breakout — high opportunity |",
        "| 📈 RISING | ≥ 5 | Growing traction — worth watching |",
        "| ➡️ STEADY | < 5 | Established or slow burn |",
        "",
        "---",
        "",
    ]

    for report in reports:
        lines += [
            f"## 📊 Topic: `{report.topic}`",
            "",
            f"*Scanned {report.total_scanned} repositories · {report.generated_at.strftime('%Y-%m-%d %H:%M UTC')}*",
            "",
            "| # | Repository | Velocity | ⭐ Stars | 🍴 Forks | Stars/Day | Language |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]

        for idx, m in enumerate(report.repositories[:15], 1):
            r = m.repo
            lang = r.language or "—"
            tier = m.tier.value
            lines.append(
                f"| {idx} | [{r.full_name}]({r.url}) | {tier} | "
                f"{r.stars:,} | {r.forks:,} | {m.stars_per_day:.1f} | {lang} |"
            )

        lines += ["", "---", ""]

    lines += [
        "## 💡 Project Idea Incubator",
        "",
        "High-impact personal projects aligned with current GitHub demand:",
        "",
    ]

    for idx, idea in enumerate(ideas, 1):
        lines += [
            f"### {idx}. {idea.title}",
            "",
            f"**Niche:** `{idea.demand_niche}` · **Difficulty:** `{idea.difficulty.value}`",
            "",
            idea.description,
            "",
            f"**Suggested Stack:** {' · '.join(f'`{s}`' for s in idea.suggested_stack)}",
            "",
            f"> 📈 **Why it matters:** {idea.why_it_matters}",
            "",
            f"> 🏆 **Portfolio value:** {idea.portfolio_value}",
            "",
        ]

    lines += [
        "---",
        "",
        "*Generated by [github-trend-radar](https://github.com) · "
        "MIT License · ⭐ Star if useful!*",
    ]

    return "\n".join(lines)


