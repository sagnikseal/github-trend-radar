TIER_BADGE_CLASS = {
    VelocityTier.BREAKING: "badge-breaking",
    VelocityTier.HIGH: "badge-high",
    VelocityTier.RISING: "badge-rising",
    VelocityTier.STEADY: "badge-steady",
}

DIFFICULTY_CLASS = {
    "Beginner": "diff-beginner",
    "Intermediate": "diff-intermediate",
    "Advanced": "diff-advanced",
}


def _repo_card(idx: int, m: VelocityMetrics) -> str:
    r = m.repo
    badge_cls = TIER_BADGE_CLASS.get(m.tier, "badge-steady")
    desc = r.description[:100] + "…" if len(r.description) > 100 else r.description
    lang = r.language or "—"
    return f"""
        <tr>
            <td class="num">{idx}</td>
            <td><a href="{r.url}" target="_blank" rel="noopener">{r.full_name}</a></td>
            <td><span class="badge {badge_cls}">{m.tier.value}</span></td>
            <td class="num">{r.stars:,}</td>
            <td class="num">{r.forks:,}</td>
            <td class="num">{m.stars_per_day:.1f}</td>
            <td><span class="lang">{lang}</span></td>
            <td class="desc">{desc}</td>
        </tr>"""


def _idea_card(idx: int, idea: ProjectIdea) -> str:
    diff_cls = DIFFICULTY_CLASS.get(idea.difficulty.value, "diff-intermediate")
    stack_tags = "".join(f'<span class="tag">{s}</span>' for s in idea.suggested_stack)
    repos = "".join(f'<code>{r}</code> ' for r in idea.related_trending_repos)
    return f"""
    <div class="idea-card" data-niche="{idea.demand_niche}">
        <div class="idea-header">
            <span class="idea-num">{idx}</span>
            <h3>{idea.title}</h3>
            <span class="badge {diff_cls}">{idea.difficulty.value}</span>
        </div>
        <div class="niche-label">{idea.demand_niche}</div>
        <p>{idea.description}</p>
        <div class="stack">{stack_tags}</div>
        <div class="idea-meta">
            <div>📈 <strong>Why it matters:</strong> {idea.why_it_matters}</div>
            <div>🏆 <strong>Portfolio value:</strong> {idea.portfolio_value}</div>
            {f'<div>🔗 <strong>Related repos:</strong> {repos}</div>' if repos.strip() else ''}
        </div>
    </div>"""


